"""Export the trained Random Forest to C for the glove ESP32.

    python -m ml.export_c
Writes firmware/glove/src/gesture_model.h (trees) and gesture_labels.h (class order).
"""
import emlearn
import joblib

from .config import MODEL_PATH, ROOT
from .features import FEATURE_NAMES

OUT = ROOT / "firmware" / "glove" / "src"


def main() -> None:
    bundle = joblib.load(MODEL_PATH)
    model = bundle["model"]
    labels = [str(c) for c in model.classes_]
    if model.n_features_in_ != len(FEATURE_NAMES):
        raise SystemExit(f"Model has {model.n_features_in_} features, features.py defines {len(FEATURE_NAMES)}")

    OUT.mkdir(parents=True, exist_ok=True)
    # float features, 8-bit leaves = soft voting, so the C side gets a probability like predict_proba
    emlearn.convert(model, method="inline", dtype="float", leaf_bits=8).save(
        file=str(OUT / "gesture_model.h"), name="gesture")

    lines = [
        "/* Generated by ml/export_c.py - do not edit. Class order = model class order. */",
        "#ifndef GESTURE_LABELS_H",
        "#define GESTURE_LABELS_H",
        "",
        f"#define GESTURE_COUNT {len(labels)}",
        f"#define GESTURE_MODEL_FEATURES {model.n_features_in_}",
        f"#define GESTURE_WINDOW {bundle['window']}",
        f"#define GESTURE_STEP {bundle['step']}",
        "",
        "enum {",
        *[f"    GESTURE_{name.upper()} = {i}," for i, name in enumerate(labels)],
        "};",
        "",
        "static const char *const GESTURE_NAMES[GESTURE_COUNT] = {",
        *[f'    "{name}",' for name in labels],
        "};",
        "",
        "#endif",
        "",
    ]
    (OUT / "gesture_labels.h").write_text("\n".join(lines), encoding="utf-8")
    size_kb = (OUT / "gesture_model.h").stat().st_size // 1024
    print(f"{len(model.estimators_)} trees, {len(labels)} classes {labels}, header {size_kb} KB")
    print(f"Written in {OUT}")


if __name__ == "__main__":
    main()